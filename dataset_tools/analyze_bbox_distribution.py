#!/usr/bin/env python3
"""
Bounding Box Distribution Analysis Script

This script analyzes the distribution of bounding boxes across all datasets 
generated by prepare_dataset.py. The bounding boxes are stored in groundtruth.txt
files in CSV format: x,y,w,h

Author: Generated for Event-RGB Catching Dataset Analysis
"""

import os
import csv
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from collections import defaultdict
import pandas as pd
from pathlib import Path

def load_all_bboxes(dataset_root):
    """
    Load all bounding boxes from all groundtruth.txt files in the dataset directory.
    
    Args:
        dataset_root (str): Path to the dataset root directory
        
    Returns:
        dict: Dictionary with dataset indices as keys and bbox data as values
    """
    all_bboxes = {}
    dataset_dirs = []
    
    # Find all dataset directories (0, 1, 2, ...)
    for item in os.listdir(dataset_root):
        item_path = os.path.join(dataset_root, item)
        if os.path.isdir(item_path) and item.isdigit():
            dataset_dirs.append(int(item))
    
    dataset_dirs.sort()
    print(f"Found {len(dataset_dirs)} dataset directories: {dataset_dirs}")
    
    total_frames = 0
    total_valid_bboxes = 0
    
    for dataset_idx in dataset_dirs:
        groundtruth_path = os.path.join(dataset_root, str(dataset_idx), 'groundtruth.txt')
        
        if not os.path.exists(groundtruth_path):
            print(f"Warning: {groundtruth_path} not found, skipping dataset {dataset_idx}")
            continue
            
        bboxes = []
        try:
            with open(groundtruth_path, 'r', newline='') as f:
                reader = csv.reader(f)
                for row_idx, row in enumerate(reader):
                    if len(row) == 4:
                        try:
                            x, y, w, h = map(int, row)
                            bboxes.append([x, y, w, h])
                            total_frames += 1
                            if not (x == 0 and y == 0 and w == 0 and h == 0):
                                total_valid_bboxes += 1
                        except ValueError:
                            print(f"Warning: Invalid bbox data in {groundtruth_path} row {row_idx}: {row}")
                    else:
                        print(f"Warning: Invalid row format in {groundtruth_path} row {row_idx}: {row}")
        except Exception as e:
            print(f"Error reading {groundtruth_path}: {e}")
            continue
            
        all_bboxes[dataset_idx] = np.array(bboxes)
        print(f"Dataset {dataset_idx}: {len(bboxes)} frames, {np.sum((np.array(bboxes) != 0).any(axis=1))} with valid bboxes")
    
    print(f"\nTotal: {total_frames} frames, {total_valid_bboxes} with valid bounding boxes")
    print(f"Valid bbox ratio: {total_valid_bboxes/total_frames*100:.2f}%")
    
    return all_bboxes

def analyze_bbox_statistics(all_bboxes):
    """
    Compute comprehensive statistics for bounding box distribution.
    
    Args:
        all_bboxes (dict): Dictionary of bounding box data per dataset
        
    Returns:
        dict: Dictionary containing various statistics
    """
    stats = {
        'total_frames': 0,
        'total_valid_bboxes': 0,
        'bbox_centers': [],
        'bbox_sizes': [],
        'bbox_aspects': [],
        'bbox_areas': [],
        'x_positions': [],
        'y_positions': [],
        'widths': [],
        'heights': [],
        'per_dataset_stats': {}
    }
    
    for dataset_idx, bboxes in all_bboxes.items():
        dataset_stats = {
            'total_frames': len(bboxes),
            'valid_bboxes': 0,
            'avg_bbox_area': 0,
            'avg_aspect_ratio': 0
        }
        
        stats['total_frames'] += len(bboxes)
        
        # Filter out invalid bounding boxes (0,0,0,0)
        valid_mask = (bboxes != 0).any(axis=1)
        valid_bboxes = bboxes[valid_mask]
        
        if len(valid_bboxes) > 0:
            stats['total_valid_bboxes'] += len(valid_bboxes)
            dataset_stats['valid_bboxes'] = len(valid_bboxes)
            
            # Extract bbox components
            x, y, w, h = valid_bboxes[:, 0], valid_bboxes[:, 1], valid_bboxes[:, 2], valid_bboxes[:, 3]
            
            # Bbox centers
            centers = np.column_stack([(x + w/2), (y + h/2)])
            stats['bbox_centers'].extend(centers.tolist())
            
            # Bbox sizes and properties
            areas = w * h
            aspects = w / np.maximum(h, 1)  # Avoid division by zero
            
            stats['bbox_areas'].extend(areas.tolist())
            stats['bbox_aspects'].extend(aspects.tolist())
            stats['x_positions'].extend(x.tolist())
            stats['y_positions'].extend(y.tolist())
            stats['widths'].extend(w.tolist())
            stats['heights'].extend(h.tolist())
            
            # Dataset-specific stats
            dataset_stats['avg_bbox_area'] = np.mean(areas)
            dataset_stats['avg_aspect_ratio'] = np.mean(aspects)
        
        stats['per_dataset_stats'][dataset_idx] = dataset_stats
    
    # Convert lists to numpy arrays for easier analysis
    for key in ['bbox_centers', 'bbox_areas', 'bbox_aspects', 'x_positions', 
                'y_positions', 'widths', 'heights']:
        if stats[key]:
            stats[key] = np.array(stats[key])
        else:
            stats[key] = np.array([])
    
    return stats

def create_distribution_plots(stats, output_dir):
    """
    Create comprehensive visualization plots for bounding box distribution.
    
    Args:
        stats (dict): Statistics computed from analyze_bbox_statistics
        output_dir (str): Directory to save plot images
    """
    os.makedirs(output_dir, exist_ok=True)
    
    # Set up the plotting style
    plt.style.use('default')
    sns.set_palette("husl")
    
    # 1. Bounding Box Center Distribution (Heatmap)
    if len(stats['bbox_centers']) > 0:
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(15, 6))
        
        centers = stats['bbox_centers']
        
        # 2D histogram of centers
        h, xedges, yedges = np.histogram2d(centers[:, 0], centers[:, 1], bins=50)
        extent = [xedges[0], xedges[-1], yedges[0], yedges[-1]]  # Standard extent
        
        im1 = ax1.imshow(h.T, extent=extent, origin='upper', cmap='hot', interpolation='bilinear')
        ax1.set_title('Bounding Box Center Distribution (Heatmap)')
        ax1.set_xlabel('X Position (pixels)')
        ax1.set_ylabel('Y Position (pixels)')
        # No need for invert_yaxis() when using origin='upper'
        plt.colorbar(im1, ax=ax1, label='Frequency')
        
        # Scatter plot of centers
        ax2.scatter(centers[:, 0], centers[:, 1], alpha=0.5, s=1)
        ax2.set_title('Bounding Box Center Scatter Plot')
        ax2.set_xlabel('X Position (pixels)')
        ax2.set_ylabel('Y Position (pixels)')
        ax2.invert_yaxis()  # Ensure Y-axis is inverted (0 at top) for image coordinates
        ax2.grid(True, alpha=0.3)
        
        plt.tight_layout()
        plt.savefig(os.path.join(output_dir, 'bbox_center_distribution.png'), dpi=300, bbox_inches='tight')
        plt.close()
    
    # 2. Size Distribution
    if len(stats['widths']) > 0 and len(stats['heights']) > 0:
        fig, ((ax1, ax2), (ax3, ax4)) = plt.subplots(2, 2, figsize=(15, 12))
        
        # Width distribution
        ax1.hist(stats['widths'], bins=50, alpha=0.7, edgecolor='black')
        ax1.set_title('Bounding Box Width Distribution')
        ax1.set_xlabel('Width (pixels)')
        ax1.set_ylabel('Frequency')
        ax1.grid(True, alpha=0.3)
        
        # Height distribution
        ax2.hist(stats['heights'], bins=50, alpha=0.7, edgecolor='black')
        ax2.set_title('Bounding Box Height Distribution')
        ax2.set_xlabel('Height (pixels)')
        ax2.set_ylabel('Frequency')
        ax2.grid(True, alpha=0.3)
        
        # Area distribution
        if len(stats['bbox_areas']) > 0:
            ax3.hist(stats['bbox_areas'], bins=50, alpha=0.7, edgecolor='black')
            ax3.set_title('Bounding Box Area Distribution')
            ax3.set_xlabel('Area (square pixels)')
            ax3.set_ylabel('Frequency')
            ax3.grid(True, alpha=0.3)
        
        # Aspect ratio distribution
        if len(stats['bbox_aspects']) > 0:
            ax4.hist(stats['bbox_aspects'], bins=50, alpha=0.7, edgecolor='black')
            ax4.set_title('Bounding Box Aspect Ratio Distribution')
            ax4.set_xlabel('Aspect Ratio (Width/Height)')
            ax4.set_ylabel('Frequency')
            ax4.grid(True, alpha=0.3)
        
        plt.tight_layout()
        plt.savefig(os.path.join(output_dir, 'bbox_size_distribution.png'), dpi=300, bbox_inches='tight')
        plt.close()
    
    # 3. Width vs Height scatter plot
    if len(stats['widths']) > 0 and len(stats['heights']) > 0:
        plt.figure(figsize=(10, 8))
        plt.scatter(stats['widths'], stats['heights'], alpha=0.6, s=10)
        plt.xlabel('Width (pixels)')
        plt.ylabel('Height (pixels)')
        plt.title('Bounding Box Width vs Height')
        plt.grid(True, alpha=0.3)
        
        # Add diagonal line for square boxes
        max_val = max(np.max(stats['widths']), np.max(stats['heights']))
        plt.plot([0, max_val], [0, max_val], 'r--', alpha=0.5, label='Square boxes')
        plt.legend()
        
        plt.tight_layout()
        plt.savefig(os.path.join(output_dir, 'bbox_width_vs_height.png'), dpi=300, bbox_inches='tight')
        plt.close()
    
    # 4. Per-dataset statistics
    if stats['per_dataset_stats']:
        datasets = list(stats['per_dataset_stats'].keys())
        valid_counts = [stats['per_dataset_stats'][d]['valid_bboxes'] for d in datasets]
        total_counts = [stats['per_dataset_stats'][d]['total_frames'] for d in datasets]
        
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(15, 6))
        
        # Valid bbox count per dataset
        ax1.bar(datasets, valid_counts)
        ax1.set_title('Valid Bounding Boxes per Dataset')
        ax1.set_xlabel('Dataset Index')
        ax1.set_ylabel('Number of Valid Bounding Boxes')
        ax1.grid(True, alpha=0.3)
        
        # Valid bbox ratio per dataset
        ratios = [v/t*100 if t > 0 else 0 for v, t in zip(valid_counts, total_counts)]
        ax2.bar(datasets, ratios)
        ax2.set_title('Valid Bounding Box Ratio per Dataset')
        ax2.set_xlabel('Dataset Index')
        ax2.set_ylabel('Valid Bbox Ratio (%)')
        ax2.grid(True, alpha=0.3)
        
        plt.tight_layout()
        plt.savefig(os.path.join(output_dir, 'per_dataset_statistics.png'), dpi=300, bbox_inches='tight')
        plt.close()

def generate_summary_report(stats, output_file):
    """
    Generate a comprehensive text summary report.
    
    Args:
        stats (dict): Statistics computed from analyze_bbox_statistics
        output_file (str): Path to save the summary report
    """
    with open(output_file, 'w') as f:
        f.write("="*80 + "\n")
        f.write("BOUNDING BOX DISTRIBUTION ANALYSIS REPORT\n")
        f.write("="*80 + "\n\n")
        
        f.write("GENERAL STATISTICS:\n")
        f.write("-" * 40 + "\n")
        f.write(f"Total Frames: {stats['total_frames']}\n")
        f.write(f"Total Valid Bounding Boxes: {stats['total_valid_bboxes']}\n")
        if stats['total_frames'] > 0:
            f.write(f"Valid Bbox Ratio: {stats['total_valid_bboxes']/stats['total_frames']*100:.2f}%\n")
        f.write(f"Number of Datasets: {len(stats['per_dataset_stats'])}\n\n")
        
        if len(stats['bbox_areas']) > 0:
            f.write("BOUNDING BOX SIZE STATISTICS:\n")
            f.write("-" * 40 + "\n")
            f.write(f"Width - Mean: {np.mean(stats['widths']):.2f}, Std: {np.std(stats['widths']):.2f}\n")
            f.write(f"Width - Min: {np.min(stats['widths'])}, Max: {np.max(stats['widths'])}\n")
            f.write(f"Height - Mean: {np.mean(stats['heights']):.2f}, Std: {np.std(stats['heights']):.2f}\n")
            f.write(f"Height - Min: {np.min(stats['heights'])}, Max: {np.max(stats['heights'])}\n")
            f.write(f"Area - Mean: {np.mean(stats['bbox_areas']):.2f}, Std: {np.std(stats['bbox_areas']):.2f}\n")
            f.write(f"Area - Min: {np.min(stats['bbox_areas']):.2f}, Max: {np.max(stats['bbox_areas']):.2f}\n")
            f.write(f"Aspect Ratio - Mean: {np.mean(stats['bbox_aspects']):.2f}, Std: {np.std(stats['bbox_aspects']):.2f}\n\n")
        
        if len(stats['bbox_centers']) > 0:
            f.write("BOUNDING BOX POSITION STATISTICS:\n")
            f.write("-" * 40 + "\n")
            centers = stats['bbox_centers']
            f.write(f"Center X - Mean: {np.mean(centers[:, 0]):.2f}, Std: {np.std(centers[:, 0]):.2f}\n")
            f.write(f"Center Y - Mean: {np.mean(centers[:, 1]):.2f}, Std: {np.std(centers[:, 1]):.2f}\n")
            f.write(f"X Position - Min: {np.min(stats['x_positions'])}, Max: {np.max(stats['x_positions'])}\n")
            f.write(f"Y Position - Min: {np.min(stats['y_positions'])}, Max: {np.max(stats['y_positions'])}\n\n")
        
        f.write("PER-DATASET STATISTICS:\n")
        f.write("-" * 40 + "\n")
        f.write(f"{'Dataset':<8} {'Frames':<8} {'Valid':<8} {'Ratio':<8} {'Avg Area':<12} {'Avg Aspect':<12}\n")
        f.write("-" * 60 + "\n")
        
        for dataset_idx, dataset_stats in stats['per_dataset_stats'].items():
            ratio = dataset_stats['valid_bboxes'] / dataset_stats['total_frames'] * 100 if dataset_stats['total_frames'] > 0 else 0
            f.write(f"{dataset_idx:<8} {dataset_stats['total_frames']:<8} {dataset_stats['valid_bboxes']:<8} {ratio:<7.1f}% "
                   f"{dataset_stats['avg_bbox_area']:<12.1f} {dataset_stats['avg_aspect_ratio']:<12.2f}\n")

def main():
    """
    Main function to run the bounding box distribution analysis.
    """
    dataset_root = "/media/xinchi/data/Event_RGB_catching_data/selected_dataset"
    output_dir = "bbox_analysis_output"
    
    print("Starting Bounding Box Distribution Analysis...")
    print(f"Dataset root: {dataset_root}")
    print(f"Output directory: {output_dir}")
    
    # Load all bounding boxes
    all_bboxes = load_all_bboxes(dataset_root)
    
    if not all_bboxes:
        print("No bounding box data found. Exiting.")
        return
    
    # Analyze statistics
    print("\nAnalyzing bounding box statistics...")
    stats = analyze_bbox_statistics(all_bboxes)
    
    # Create output directory
    os.makedirs(output_dir, exist_ok=True)
    
    # Generate plots
    print("\nGenerating distribution plots...")
    create_distribution_plots(stats, output_dir)
    
    # Generate summary report
    print("\nGenerating summary report...")
    summary_file = os.path.join(output_dir, "bbox_distribution_report.txt")
    generate_summary_report(stats, summary_file)
    
    print(f"\nAnalysis complete! Results saved to: {output_dir}")
    print(f"Summary report: {summary_file}")
    print(f"Visualization plots saved as PNG files in: {output_dir}")

if __name__ == "__main__":
    main()